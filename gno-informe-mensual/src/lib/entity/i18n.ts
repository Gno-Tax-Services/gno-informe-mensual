export function t(lang: Lang, key: string, params: Record<string, string | number> = {}): string {
  const raw = DICT[lang][key] ?? DICT.es[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? `{${k}}`));
}

